import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';

// Exercise the production helper without adding a new runtime dependency.
const data = JSON.parse(fs.readFileSync(new URL('../src/data/gibson-shipments.json', import.meta.url)));
const source = fs.readFileSync(new URL('../src/lib/gibson-shipments.ts', import.meta.url), 'utf8')
  .replace("import raw from '../data/gibson-shipments.json';", `const raw=${JSON.stringify(data)};`);
const compiled = ts.transpile(source, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 });
const { lookupShipments: lookup, shipmentCSV } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);

assert.equal(lookup('les-paul-model-standard-1952-to-1960', 'all', '1958').count, 434);
assert.equal(lookup('les-paul-model-standard-1952-to-1960', 'Goldtop', '1958').count, null);
assert.equal(lookup('les-paul-model-standard-1952-to-1960', 'Sunburst', '1958').status, 'Finish not separated');
assert.equal(lookup('les-paul-deluxe', 'Goldtop', '1976', 'Standard listing').count, 34);
assert.equal(lookup('les-paul-deluxe', 'all', '1976').count, 172);
assert.equal(lookup('les-paul-deluxe', 'Goldtop', '1976', 'Left-handed').count, 23);
assert.equal(lookup('les-paul-deluxe', 'Goldtop', '1976').unallocated.length, 2);
assert.equal(lookup('les-paul-deluxe', 'Goldtop', '1976', 'Left-handed').unallocated.length, 0);
assert.equal(lookup('es-335td', 'Sunburst', '1971').unallocated.length, 1);
assert.equal(lookup('les-paul-junior-original-slab-body', 'all', '1959').count, 4364);
assert.equal(lookup('es-355td-mono', 'all', '1959').count, 177);
assert.equal(lookup('es-355tdsv-stereo', 'all', '1959').count, 123);
assert.equal(lookup('es-355td-mono', 'Cherry', '1959').count, null);
assert.equal(lookup('explorer', 'all', '1958').count, 19);
assert.equal(lookup('moderne', 'all', '1958').count, null);
assert.equal(lookup('byrdland', 'Sunburst', '1959').count, null);
assert.equal(lookup('byrdland', 'Natural', '1959').count, 34);
assert.equal(lookup('byrdland', 'all', 'all').count, null);
assert.equal(lookup('lg-0', 'all', '1970').count, null);
assert.equal(lookup('j-185', 'Sunburst', '1959').count, 0);
assert.equal(lookup('les-paul-55', 'all', '1975').count, 0);
assert.equal(lookup('l-5c-acoustic-archtop', 'Natural', '1961').count, 5);
assert.equal(lookup('l-5ces', 'Natural', '1961').count, 13);
assert.equal(lookup('es-5', 'Sunburst', '1951').count, 88);
assert.equal(lookup('sg-les-paul-standard', 'all', '1970').count, 6677);
assert.equal(lookup('sg-special', 'all', '1970').count, 4982);
assert.equal(lookup('firebird-iii', 'Pelham Blue', '1965').count, null);
assert(!lookup('lg-0', 'all', 'all').years.includes(1970));
assert(lookup('lg-0', 'all', 'all').gaps.includes(1970));

assert.equal(new Set(data.records.map(row => [row.model, row.year, row.finish, row.variant].join('|'))).size, data.records.length);
for (const row of data.records) {
  assert(Number.isInteger(row.count) && row.count >= 0);
  assert(row.year >= data.coverage.from && row.year <= data.coverage.to);
  assert(data.models.some(model => model.id === row.model));
  assert(row.sources.length);
  for (const id of row.sources) assert(data.sources.some(source => source.id === id));
}

// These are separately transcribed printed totals, not values generated by the lookup.
const totals = JSON.parse(fs.readFileSync(new URL('./fixtures/gibson-shipment-totals.json', import.meta.url)));
for (const check of totals) {
  const sum = check.models.reduce((value, model) => value + (lookup(model, 'all', String(check.year)).count ?? 0), 0);
  assert.equal(sum, check.total, `${check.label}, ${check.year}: ${check.source}`);
}
const csv = shipmentCSV(lookup('byrdland', 'Sunburst', '1959').rows);
assert(csv.includes('"","disputed"'));
assert(csv.includes('https://www.guitarhq.com/shippin1.html'));
assert(csv.includes('46 (byrdland)'));
console.log(`PASS: ${data.records.length} records, category and source integrity, lookup boundaries, CSV dispute handling, and ${totals.length} independently printed annual totals.`);
